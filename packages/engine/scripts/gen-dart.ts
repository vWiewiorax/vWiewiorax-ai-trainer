/**
 * Generates packages/trainer_engine/lib/src/exercises.dart from the TypeScript
 * exercise definitions so both engines share one source of truth.
 * Usage: npx tsx scripts/gen-dart.ts
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { EXERCISES } from "../src/exercises";
import type { ErrorDefinition, ExerciseDefinition, RuleCondition } from "../src/core/types";

const VIEW: Record<string, string> = { side: "side", front: "front", rear: "rear", "front-side": "frontSide", unknown: "unknown" };
const s = (x: string) => `'${x.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;
const n = (x: number) => (Number.isInteger(x) ? `${x}.0` : `${x}`);
const views = (v: readonly string[]) => `[${v.map((x) => `CameraView.${VIEW[x]}`).join(", ")}]`;
const strs = (v: readonly string[]) => `[${v.map(s).join(", ")}]`;
const pair = (p: readonly number[]) => `(${n(p[0]!)}, ${n(p[1]!)})`;

function cond(c: RuleCondition): string {
  const a: string[] = [`kind: ${s(c.kind)}`, `phase: ${s(c.phase)}`, `bands: ${pair(c.bands)}`];
  const o = c as unknown as Record<string, unknown>;
  if (o.window) a.push(`window: ${pair(o.window as number[])}`);
  for (const k of ["feature", "stat", "compare", "numerator", "denominator", "left", "right"]) if (o[k] !== undefined) a.push(`${k}: ${s(o[k] as string)}`);
  for (const k of ["threshold", "thresholdMs", "minDenominator", "minNumerator", "tolerance"]) if (o[k] !== undefined) a.push(`${k}: ${n(o[k] as number)}`);
  if (o.minPreviousReps !== undefined) a.push(`minPreviousReps: ${o.minPreviousReps}`);
  return `RuleCondition(${a.join(", ")})`;
}

function rule(r: ErrorDefinition): string {
  const a = [
    `type: ${s(r.type)}`, `label: ${s(r.label)}`, `category: ${s(r.category)}`, `importance: ${n(r.importance)}`,
    `views: ${views(r.views)}`, `reliability: ${n(r.reliability)}`, `minConfidence: ${n(r.minConfidence)}`,
    `condition: ${cond(r.condition as RuleCondition)}`, `description: ${s(r.description)}`, `correction: ${s(r.correction)}`, `voice: ${s(r.voice)}`,
  ];
  if (r.recommendedAction) a.push(`recommendedAction: ${s(r.recommendedAction)}`);
  if (r.safetyCritical) a.push("safetyCritical: true");
  if (r.adjustable) a.push(`adjustable: Adjustable(${n(r.adjustable.min)}, ${n(r.adjustable.max)})`);
  return `    ErrorDefinition(\n      ${a.join(",\n      ")},\n    )`;
}

function def(d: ExerciseDefinition, name: string): string {
  const r = d.repetition;
  const rep = [
    `signal: ${s(r.signal)}`, `startPosition: ${s(r.startPosition)}`, `highThreshold: ${n(r.highThreshold)}`, `lowThreshold: ${n(r.lowThreshold)}`,
    `hysteresis: ${n(r.hysteresis)}`, `minPhaseMs: ${n(r.minPhaseMs)}`, `minRepMs: ${n(r.minRepMs)}`, `maxRepMs: ${n(r.maxRepMs)}`, `minRange: ${n(r.minRange)}`,
    `phases: RepPhases(low: ${s(r.phases.low)}, rising: ${s(r.phases.rising)}, high: ${s(r.phases.high)}, falling: ${s(r.phases.falling)})`,
    `countAt: ${s(r.countAt)}`,
  ];
  if (r.requireReturn) rep.push("requireReturn: true");
  if (r.onsetFeature) rep.push(`onsetFeature: ${s(r.onsetFeature)}`);
  if (r.onsetEpsilon !== undefined) rep.push(`onsetEpsilon: ${n(r.onsetEpsilon)}`);
  const scoring = Object.entries(d.scoringConfiguration).map(([k, v]) => `${s(k)}: ${n(v as number)}`).join(", ");
  const rec = d.recognition
    .map((p) => `RecognitionPredicate(feature: ${s(p.feature)}, stat: ${s(p.stat)}${p.min !== undefined ? `, min: ${n(p.min)}` : ""}${p.max !== undefined ? `, max: ${n(p.max)}` : ""}, weight: ${n(p.weight)})`)
    .join(",\n    ");
  return `const ${name} = ExerciseDefinition(
  id: ${s(d.id)},
  name: ${s(d.name)},
  family: ${s(d.family)},
  requiredLandmarks: ${strs(d.requiredLandmarks)},
  requireSides: ${s(d.requireSides ?? "both")},
  preferredCameraAngle: CameraView.${VIEW[d.preferredCameraAngle]},
  allowedCameraAngles: ${views(d.allowedCameraAngles)},
  cameraSetup: ${s(d.cameraSetup)},
  calibrationPose: ${s(d.calibrationPose)},
  occludableLandmarks: ${strs(d.occludableLandmarks ?? [])},
  movementPhases: [${d.movementPhases.map((p) => `PhaseDefinition(${s(p.id)}, PhaseKind.${p.kind}, ${s(p.label)})`).join(", ")}],
  repetition: RepetitionConfig(${rep.join(", ")}),
  scoringConfiguration: {${scoring}},
  evaluationRules: [
${d.evaluationRules.map(rule).join(",\n")},
  ],
  recognition: [
    ${rec},
  ],
  liveChecks: [${(d.liveChecks ?? []).map((c) => `LiveCheck(${s(c.rule)}, ${strs(c.phases)}, ${n(c.persistMs)})`).join(", ")}],
  comparisonFeatures: ${strs(d.comparisonFeatures ?? [])},
  keyCheckpoints: ${strs(d.keyCheckpoints ?? [])},
);
`;
}

const camel = (id: string) => id.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
const defs = Object.values(EXERCISES);
const out = `// GENERATED by packages/engine/scripts/gen-dart.ts - do not edit by hand.
import 'types.dart';

${defs.map((d) => def(d, camel(d.id))).join("\n")}
const exercises = <String, ExerciseDefinition>{
${defs.map((d) => `  ${s(d.id)}: ${camel(d.id)},`).join("\n")}
};
`;
writeFileSync(resolve(import.meta.dirname, "../../trainer_engine/lib/src/exercises.dart"), out);
console.log(`wrote ${defs.length} exercises`);
