/**
 * Runs the engine over every annotated landmark sequence (validation/annotations.json) and the
 * SYNTHETIC fault suite, then writes validation/RESULTS.md. Real and synthetic metrics are kept apart.
 *   npm run validate -w @trainer/engine
 */
import { readFileSync, existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  aggregateMetrics,
  compareToAnnotation,
  deadlift,
  generateSyntheticDeadlift,
  runSequence,
  applySceneCuts,
  SYNTHETIC_LABEL,
  type DatasetAnnotation,
  type DeadliftFault,
  type PoseFrame,
  type SequenceResult,
} from "../src";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "validation");
const annotations = JSON.parse(readFileSync(join(root, "annotations.json"), "utf8")) as DatasetAnnotation[];

const real: SequenceResult[] = [];
const skipped: string[] = [];
for (const ann of annotations) {
  const file = ann.landmarksFile ? join(root, ann.landmarksFile) : null;
  if (!file || !existsSync(file)) {
    skipped.push(ann.id);
    continue;
  }
  const { frames } = JSON.parse(readFileSync(file, "utf8")) as { frames: PoseFrame[] };
  real.push(compareToAnnotation(runSequence(applySceneCuts(frames, ann.sceneCutsMs), { exercise: deadlift }), ann));
}

const FAULTS: [DeadliftFault, string[]][] = [
  ["none", []],
  ["hipRiseEarly", ["HIP_RISE_TOO_EARLY", "TRUNK_ANGLE_CHANGE"]],
  ["incompleteLockout", ["INCOMPLETE_LOCKOUT"]],
  ["backwardLean", ["EXCESSIVE_BACKWARD_LEAN"]],
  ["fastLowering", ["UNCONTROLLED_LOWERING"]],
  ["trunkChordLoss", ["EXCESSIVE_TRUNK_FLEXION"]],
  ["partialRange", ["INCOMPLETE_RANGE_OF_MOTION"]],
];
const synthetic: SequenceResult[] = [];
for (const [fault, expected] of FAULTS) {
  for (const variant of [{ seed: 1 }, { seed: 2, mirrored: true }, { seed: 3, facing: -1 as const, scale: 0.6 }, { seed: 4, noise: 0.006 }]) {
    const reps = 3;
    const { frames } = generateSyntheticDeadlift({ reps, fault, ...variant });
    const ann: DatasetAnnotation = {
      id: `synthetic:${fault}:${JSON.stringify(variant)}`,
      kind: "synthetic",
      source: SYNTHETIC_LABEL,
      exercise: deadlift.id,
      cameraView: "side",
      expectedRepCount: fault === "partialRange" ? 0 : reps,
      errors: expected.map((type) => ({ type, annotatorConfidence: 1 })),
      annotator: "generator",
      annotationConfidence: 1,
    };
    synthetic.push(compareToAnnotation(runSequence(frames, { exercise: deadlift }), ann));
  }
}

const pct = (x: number | null) => (x === null ? "-" : `${Math.round(x * 100)}%`);
const table = (rows: SequenceResult[]) =>
  [
    "| sequence | reps expected / detected | score | confidence | usable frames | view | detected errors | FP | FN |",
    "|---|---|---|---|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| ${r.id} | ${r.expectedReps} / ${r.detectedReps} | ${r.averageScore ?? "-"} | ${pct(r.analysisConfidence)} | ${pct(r.usableFrameRatio)} | ${r.dominantView} | ${r.detectedErrors.join(", ") || "-"} | ${r.falsePositives.join(", ") || "-"} | ${r.falseNegatives.join(", ") || "-"} |`,
    ),
  ].join("\n");
const summary = (rows: SequenceResult[]) => {
  const m = aggregateMetrics(rows);
  return `sequences ${m.sequences}, exact rep count ${m.repCountExact}/${m.sequences}, rep MAE ${m.repCountMeanAbsError.toFixed(2)}, error precision ${pct(m.errorPrecision)}, recall ${pct(m.errorRecall)}, FP ${m.falsePositives}, FN ${m.falseNegatives}, scored-when-unscorable ${m.scoredWhenUnscorable}`;
};

const md = `# Validation results

Generated by \`npm run validate -w @trainer/engine\`.

## Real recordings (landmarks extracted with MediaPipe Pose Landmarker full, 30 samples/s)

The real set is tiny and labelled by a non-expert. It checks robustness and behaviour on real pose
output; it is NOT a measure of accuracy. See annotations.json for label confidence and conditions.

${summary(real)}

${table(real)}
${skipped.length ? `\nMissing landmark files (not evaluated): ${skipped.join(", ")}\n` : ""}
## ${SYNTHETIC_LABEL}

Generated planar stick figures with known faults. These only verify the logic of the code.

${summary(synthetic)}

${table(synthetic)}
`;
writeFileSync(join(root, "RESULTS.md"), md);
console.log(`REAL: ${summary(real)}`);
console.log(table(real));
console.log(`SYNTHETIC: ${summary(synthetic)}`);
for (const r of synthetic) if (r.repCountError || r.falsePositives.length || r.falseNegatives.length) console.log("  mismatch", r.id, r.detectedReps, r.falsePositives, r.falseNegatives);
